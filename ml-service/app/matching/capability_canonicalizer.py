EMBEDDING_MODEL_NAME = (
    "all-MiniLM-L6-v2"
)

GROQ_MODEL_NAME = (
    "openai/gpt-oss-120b"
)

# Number of O*NET candidate capabilities generated by
# embedding similarity before the LLM makes the decision.
EMBEDDING_CANDIDATE_COUNT = 8

# Minimum embedding similarity required for a capability
# to become a candidate.
EMBEDDING_THRESHOLD = 0.35

# Maximum canonical O*NET capabilities returned for one
# LLM-generated capability.
MAX_CANONICAL_CAPABILITIES = 3

# Maximum amount of occupation evidence retained for each
# O*NET capability.
MAX_CONTEXT_OCCUPATIONS = 5

# Maximum task snippets retained per occupation.
MAX_CONTEXT_TASKS = 2


# =========================================================
# Normalization
# =========================================================

def normalize_text(
    text: str,
) -> str:
    """
    Normalize text for exact comparisons and deduplication.
    """

    text = str(
        text
    ).lower().strip()

    text = text.replace(
        "-",
        " ",
    )

    text = re.sub(
        r"[^a-z0-9\s]",
        "",
        text,
    )

    text = re.sub(
        r"\s+",
        " ",
        text,
    )

    return text.strip()


# =========================================================
# Groq
