def load_occupations() -> List[Dict]:
    """
    Load processed O*NET occupation data.
    """

    if not OCCUPATIONS_PATH.exists():
        raise FileNotFoundError(
            "Could not find occupations.json:\n"
            f"{OCCUPATIONS_PATH}"
        )

    with open(
        OCCUPATIONS_PATH,
        "r",
        encoding="utf-8",
    ) as f:
        return json.load(f)


# =========================================================
# Build capability vocabulary
# =========================================================

def build_onet_capability_vocabulary(
    occupations: List[Dict],
) -> List[str]:
    """
    Build the unique O*NET capability vocabulary from
    essential and transferable skills.
    """

    capabilities = set()

    for occupation in occupations:

        for skill in occupation.get(
            "essential_skills",
            [],
        ):

            name = skill.get(
                "name"
            )

            if name:
                capabilities.add(
                    name.strip()
                )

        for skill in occupation.get(
            "transferable_skills",
            [],
        ):

            name = skill.get(
                "name"
            )

            if name:
                capabilities.add(
                    name.strip()
                )

    return sorted(
        capabilities
    )


# =========================================================
# Build O*NET capability context
# =========================================================

def build_capability_context(
    occupations: List[Dict],
) -> Dict[str, Dict]:
    """
    Build contextual information for every O*NET capability.

    Example:

        "Operations Analysis": {
            "occupations": [
                "Management Analysts",
                "Data Scientists"
            ],
            "tasks": [
                "...",
                "..."
            ]
        }

    This gives the LLM actual occupational context when
    choosing between semantically similar capabilities.
    """

    context = {}

    for occupation in occupations:

        occupation_title = occupation.get(
            "title",
            "",
        )

        tasks = occupation.get(
            "tasks",
            [],
        )

        relevant_task_text = [
            str(task).strip()
            for task in tasks[:10]
            if str(task).strip()
        ]

        all_skills = []

        for skill in occupation.get(
            "essential_skills",
            [],
        ):
            all_skills.append(
                skill
            )

        for skill in occupation.get(
            "transferable_skills",
            [],
        ):
            all_skills.append(
                skill
            )

        for skill in all_skills:

            capability_name = skill.get(
                "name"
            )

            if not capability_name:
                continue

            normalized = normalize_text(
                capability_name
            )

            if normalized not in context:

                context[normalized] = {
                    "name":
                        capability_name,

                    "occupations": [],

                    "tasks": [],
                }

            entry = context[
                normalized
            ]

            if occupation_title:

                if occupation_title not in (
                    entry["occupations"]
                ):

                    if len(
                        entry["occupations"]
                    ) < MAX_CONTEXT_OCCUPATIONS:

                        entry[
                            "occupations"
                        ].append(
                            occupation_title
                        )

            for task in relevant_task_text:

                if task not in entry["tasks"]:

                    if len(
                        entry["tasks"]
                    ) < (
                        MAX_CONTEXT_OCCUPATIONS
                        * MAX_CONTEXT_TASKS
                    ):

                        entry[
                            "tasks"
                        ].append(
                            task
                        )

    return context


# =========================================================
# Embedding model
# =========================================================

def load_embedding_model():
    """
    Load the same embedding model used elsewhere in the
    project.
    """

    from sentence_transformers import (
        SentenceTransformer,
    )

    return SentenceTransformer(
        EMBEDDING_MODEL_NAME
    )


# =========================================================
# O*NET capability embeddings
# =========================================================

def build_onet_embeddings(
    capabilities: List[str],
    model,
) -> np.ndarray:
    """
    Encode O*NET capability names.
    """

    if not capabilities:

        return np.empty(
            (0, 384),
            dtype=np.float32,
        )

    embeddings = model.encode(
        capabilities,
        normalize_embeddings=True,
        convert_to_numpy=True,
    )

    return embeddings


# =========================================================
# Candidate generation
# =========================================================

def find_embedding_candidates(
    capability_name: str,
    evidence: str,
    onet_capabilities: List[str],
    onet_embeddings: np.ndarray,
    model,
) -> List[Dict]:
    """
    Generate candidate O*NET capabilities using the
    capability name AND its resume evidence.

    This is candidate generation only.

    The embedding model does NOT make the final decision.
    """

    if not onet_capabilities:
        return []

    # -----------------------------------------------------
    # IMPORTANT:
    #
    # Previously we embedded only:
    #
    #     "Data Analysis"
    #
    # Now we embed:
    #
    #     Capability: Data Analysis
    #     Evidence: Analyzed 500,000 records...
    #
    # The evidence helps disambiguate similar concepts.
    # -----------------------------------------------------

    query_text = (
        f"Capability: {capability_name}\n"
        f"Evidence: {evidence}"
    )

    query_embedding = model.encode(
        query_text,
        normalize_embeddings=True,
        convert_to_numpy=True,
    )

    similarities = (
        onet_embeddings
        @ query_embedding
    )

    ranked_indices = np.argsort(
        similarities
    )[::-1]

    candidates = []

    for index in ranked_indices:

        index = int(index)

        similarity = float(
            similarities[index]
        )

        if (
            similarity
            < EMBEDDING_THRESHOLD
        ):
            continue

        candidates.append(
            {
                "name":
                    onet_capabilities[index],

                "similarity":
                    similarity,
            }
        )

        if len(candidates) >= (
            EMBEDDING_CANDIDATE_COUNT
        ):
            break

    return candidates


# =========================================================
# Candidate context formatting
# =========================================================

def build_candidate_context(
    candidates: List[Dict],
    capability_context: Dict[str, Dict],
) -> str:
    """
    Turn candidate O*NET capabilities into concise contextual
    descriptions for the LLM.
    """

    sections = []

    for candidate in candidates:

        name = candidate[
            "name"
        ]

        similarity = candidate[
            "similarity"
        ]

        context = capability_context.get(
            normalize_text(name),
            {},
        )

        occupations = context.get(
            "occupations",
            [],
        )

        tasks = context.get(
            "tasks",
            [],
        )

        section = []

        section.append(
            f"Candidate: {name}"
        )

        section.append(
            f"Embedding similarity: "
            f"{similarity:.3f}"
        )

        if occupations:

            section.append(
                "Appears in occupations: "
                + ", ".join(
                    occupations
                )
            )

        if tasks:

            section.append(
                "Representative O*NET tasks:"
            )

            for task in tasks[:MAX_CONTEXT_TASKS]:

                section.append(
                    f"- {task}"
                )

        sections.append(
            "\n".join(section)
        )

    return "\n\n".join(
        sections
    )


# =========================================================
# Exact O*NET match
# =========================================================

def exact_match(
    capability_name: str,
    onet_capabilities: List[str],
) -> Optional[str]:
    """
    Find an exact normalized O*NET capability match.

    No broad aliases are used here.

    This prevents unsafe mappings such as:

        Data Analysis -> Operations Analysis
    """

    normalized = normalize_text(
        capability_name
    )

    if not normalized:
        return None

    for onet_name in onet_capabilities:

        if normalize_text(
            onet_name
        ) == normalized:

            return onet_name

    return None


# =========================================================
# LLM selection schema
# =========================================================

CANONICALIZATION_SCHEMA = {

    "type": "object",

    "properties": {

        "selected_capabilities": {

            "type": "array",

            "items": {

                "type": "object",

                "properties": {

                    "name": {
                        "type": "string"
                    },

                    "confidence": {
                        "type": "number",
                        "minimum": 0,
                        "maximum": 1
                    },

                    "reason": {
                        "type": "string"
                    }
                },

                "required": [
                    "name",
                    "confidence",
                    "reason",
                ],

                "additionalProperties": False,
            },
        },
    },

    "required": [
        "selected_capabilities"
    ],

    "additionalProperties": False,
}


# =========================================================
# LLM chooser
# =========================================================

def llm_choose_capabilities(
    original_capability: str,
    evidence: str,
    candidates: List[Dict],
    capability_context: Dict[str, Dict],
    client: Groq,
) -> List[Dict]:
    """
    Ask the LLM to choose zero or more O*NET capabilities
    from the candidate set.

    The LLM cannot invent capability names.
    """

    if not candidates:
        return []

    candidate_text = (
        build_candidate_context(
            candidates,
            capability_context,
        )
    )

    system_prompt = """
You are an ontology-mapping component for a career
recommendation system.

Your task is to map a resume-derived capability to one or
more canonical O*NET capabilities.

Rules:

1. You may ONLY select names from the supplied candidate list.

2. You may select zero, one, or multiple candidates.

3. Select multiple candidates only when each one is genuinely
   supported by the resume evidence.

4. Do NOT force a mapping.

5. If none of the candidates accurately represents the
   resume capability, return an empty list.

6. Use both:
   - the original capability phrase
   - the resume evidence
   - the O*NET candidate context

7. Prefer semantic meaning over word overlap.

8. Do not treat merely related words as equivalent.

Example:

"Data Analysis"
should NOT automatically become
"Systems Analysis".

"Machine Learning Modeling" may support capabilities such as
Programming, Critical Thinking, or Complex Problem Solving
only when the candidate context and evidence support them.

Return only canonical O*NET capability names from the supplied
candidate list.
"""

    user_prompt = f"""
Original resume capability:
{original_capability}

Resume evidence:
{evidence}

Candidate O*NET capabilities:
{candidate_text}

Choose the O*NET capabilities that are genuinely supported.
It is valid to choose none.
"""

    response = client.chat.completions.create(
        model=GROQ_MODEL_NAME,

        messages=[
            {
                "role": "system",
                "content": system_prompt,
            },

            {
                "role": "user",
                "content": user_prompt,
            },
        ],

        temperature=0,

        max_tokens=1200,

        response_format={
            "type": "json_schema",

            "json_schema": {
                "name":
                    "capability_canonicalization",

                "strict":
                    True,

                "schema":
                    CANONICALIZATION_SCHEMA,
            },
        },
    )

    content = (
        response
        .choices[0]
        .message
        .content
    )

    if not content:
        return []

    try:

        result = json.loads(
            content
        )

    except json.JSONDecodeError:

        return []

    selected = result.get(
        "selected_capabilities",
        [],
    )

    # -----------------------------------------------------
    # Safety validation
    # -----------------------------------------------------

    allowed = {
        normalize_text(
            candidate["name"]
        ):
            candidate
        for candidate in candidates
    }

    validated = []

    seen = set()

    for item in selected:

        name = str(
            item.get(
                "name",
                "",
            )
        ).strip()

        normalized = normalize_text(
            name
        )

        candidate = allowed.get(
            normalized
        )

        if candidate is None:
            continue

        if normalized in seen:
            continue

        llm_confidence = max(
            0.0,
            min(
                1.0,
                float(
                    item.get(
                        "confidence",
                        0.0,
                    )
                ),
            ),
        )

        validated.append(
            {
                "name":
                    candidate["name"],

                "embedding_similarity":
                    float(
                        candidate[
                            "similarity"
                        ]
                    ),

                "confidence":
                    llm_confidence,

                "reason":
                    str(
                        item.get(
                            "reason",
                            "",
                        )
                    ),
            }
        )

        seen.add(
            normalized
        )

        if len(validated) >= (
            MAX_CANONICAL_CAPABILITIES
        ):
            break

    return validated


# =========================================================
# Canonicalize one capability
# =========================================================

def canonicalize_capability(
    capability: Dict,
    onet_capabilities: List[str],
    onet_embeddings: np.ndarray,
    capability_context: Dict[str, Dict],
    embedding_model,
    groq_client: Groq,
) -> Dict:
    """
    Canonicalize a single LLM-generated capability.
    """

    original_name = str(
        capability.get(
            "name",
            "",
        )
    ).strip()

    evidence = str(
        capability.get(
            "evidence",
            "",
        )
    ).strip()

    llm_confidence = max(
        0.0,
        min(
            1.0,
            float(
                capability.get(
                    "confidence",
                    0.0,
                )
            ),
        ),
    )

    if not original_name:

        return {
            "original_name":
                "",

            "evidence":
                evidence,

            "canonical_capabilities":
                [],

            "status":
                "invalid",
        }

    # =====================================================
    # Step 1 — exact match
    # =====================================================

    exact = exact_match(
        original_name,
        onet_capabilities,
    )

    if exact:

        return {
            "original_name":
                original_name,

            "evidence":
                evidence,

            "llm_confidence":
                llm_confidence,

            "canonical_capabilities": [
                {
                    "name":
                        exact,

                    "embedding_similarity":
                        1.0,

                    "confidence":
                        llm_confidence,

                    "reason":
                        "Exact O*NET capability match.",

                    "source":
                        "exact",
                }
            ],

            "embedding_candidates":
                [],

            "status":
                "exact",
        }

    # =====================================================
    # Step 2 — semantic candidate generation
    # =====================================================

    candidates = (
        find_embedding_candidates(
            original_name,
            evidence,
            onet_capabilities,
            onet_embeddings,
            embedding_model,
        )
    )

    if not candidates:

        return {
            "original_name":
                original_name,

            "evidence":
                evidence,

            "llm_confidence":
                llm_confidence,

            "canonical_capabilities":
                [],

            "embedding_candidates":
                [],

            "status":
                "no_candidates",
        }

    # =====================================================
    # Step 3 — LLM decision
    # =====================================================

    selected = (
        llm_choose_capabilities(
            original_name,
            evidence,
            candidates,
            capability_context,
            groq_client,
        )
    )

    canonical_capabilities = []

    for item in selected:

        confidence = (
            float(
                item["confidence"]
            )
            * llm_confidence
        )

        confidence = max(
            0.0,
            min(
                1.0,
                confidence,
            ),
        )

        canonical_capabilities.append(
            {
                "name":
                    item["name"],

                "embedding_similarity":
                    item[
                        "embedding_similarity"
                    ],

                "confidence":
                    confidence,

                "reason":
                    item.get(
                        "reason",
                        "",
                    ),

                "source":
                    "embedding_plus_llm",
            }
        )

    return {
        "original_name":
            original_name,

        "evidence":
            evidence,

        "llm_confidence":
            llm_confidence,

        "canonical_capabilities":
            canonical_capabilities,

        "embedding_candidates":
            candidates,

        "status":
            (
                "semantic"
                if canonical_capabilities
                else "llm_rejected"
            ),
    }


# =========================================================
# Canonicalize all capabilities
# =========================================================

def canonicalize_capabilities(
    user_capabilities: List[Dict],
    embedding_model=None,
    groq_client: Groq | None = None,
) -> List[Dict]:
    """
    Canonicalize all LLM-generated capabilities.
    """

    if not user_capabilities:
        return []

    occupations = load_occupations()

    onet_capabilities = (
        build_onet_capability_vocabulary(
            occupations
        )
    )

    capability_context = (
        build_capability_context(
            occupations
        )
    )

    if embedding_model is None:

        embedding_model = (
            load_embedding_model()
        )

    if groq_client is None:

        groq_client = (
            get_groq_client()
        )

    onet_embeddings = (
        build_onet_embeddings(
            onet_capabilities,
            embedding_model,
        )
    )

    results = []

    for capability in user_capabilities:

        result = canonicalize_capability(
            capability,
            onet_capabilities,
            onet_embeddings,
            capability_context,
            embedding_model,
            groq_client,
        )

        results.append(
            result
        )

    return results


# =========================================================
# Convert to matcher format
# =========================================================

def get_canonical_capabilities(
    canonicalized: List[Dict],
) -> List[Dict]:
    """
    Convert detailed canonicalization output into the
    structure expected by capability_matching.py.

    If several LLM-derived capabilities map to the same
    O*NET capability, retain the strongest evidence.
    """

    strongest = {}

    for result in canonicalized:

        original_name = result.get(
            "original_name",
            "",
        )

        evidence = result.get(
            "evidence",
            "",
        )

        for canonical in result.get(
            "canonical_capabilities",
            [],
        ):

            name = str(
                canonical.get(
                    "name",
                    "",
                )
            ).strip()

            if not name:
                continue

            normalized = normalize_text(
                name
            )

            evidence_strength = max(
                0.0,
                min(
                    1.0,
                    float(
                        canonical.get(
                            "confidence",
                            0.0,
                        )
                    ),
                ),
            )

            candidate = {
                "name":
                    name,

                "evidence":
                    evidence,

                "confidence":
                    evidence_strength,

                "evidence_strength":
                    evidence_strength,

                "source":
                    canonical.get(
                        "source",
                        "llm_canonicalized",
                    ),

                "original_name":
                    original_name,

                "canonical_similarity":
                    float(
                        canonical.get(
                            "embedding_similarity",
                            0.0,
                        )
                    ),

                "reason":
                    canonical.get(
                        "reason",
                        "",
                    ),
            }

            existing = strongest.get(
                normalized
            )

            if (
                existing is None
                or candidate[
                    "evidence_strength"
                ]
                > existing[
                    "evidence_strength"
                ]
            ):

                strongest[
                    normalized
                ] = candidate

    return list(
        strongest.values()
    )


# =========================================================
# Full pipeline
# =========================================================

def analyze_and_canonicalize(
    llm_capabilities: List[Dict],
    embedding_model=None,
    groq_client: Groq | None = None,
) -> Dict:
    """
    Run the complete hybrid canonicalization pipeline.
    """

    canonicalized = (
        canonicalize_capabilities(
            llm_capabilities,
            embedding_model=
                embedding_model,
            groq_client=
                groq_client,
        )
    )

    canonical_capabilities = (
        get_canonical_capabilities(
            canonicalized
        )
    )

    return {
        "canonicalized":
            canonicalized,

        "canonical_capabilities":
            canonical_capabilities,
    }


