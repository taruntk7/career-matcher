def get_groq_client() -> Groq:
    """
    Create a Groq client from GROQ_API_KEY.
    """

    api_key = os.getenv(
        "GROQ_API_KEY"
    )

    if not api_key:
        raise RuntimeError(
            "GROQ_API_KEY was not found.\n"
            f"Expected it in:\n{ENV_PATH}"
        )

    return Groq(
        api_key=api_key
    )


# =========================================================
# O*NET loading
